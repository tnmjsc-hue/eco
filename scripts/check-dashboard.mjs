  async function mockDailyRelease(day, value, id) {
    const fixture = structuredClone(history);
    fixture.release_id = id;
    const ids = Object.keys(fixture.rows.at(-1).components);
    fixture.rows.push({ ...fixture.rows.at(-1), date: day, price_usd: 5000, score: value, core_score:value, coverage: 7,
      components: Object.fromEntries(ids.map(id=>[id,value])), reasons: Object.fromEntries(ids.map(id=>[id,null])), source_row_present: true, period_closed_at_retrieval: true });
    const hash = body => createHash('sha256').update(body).digest('hex');
    const body = JSON.stringify(fixture);
    const researchResponse = await page.request.get(new URL(`/data/extended/releases/${pointer.release_id}/research.json`, url).href);
    const researchBody = await researchResponse.text();
    const newManifest = { ...manifest, release_id: id, rows: fixture.rows.length, score_rows: fixture.rows.filter(r => r.score !== null).length,
      last_valid_score_date: day, last_valid_score: value, last_observation_date: day, last_requested_date: day,
      files: { 'history.json': hash(body), 'research.json': hash(researchBody) } };
    const manifestBody = JSON.stringify(newManifest);
    const newPointer = { ...pointer, release_id: id, manifest_url: `/data/extended/releases/${id}/manifest.json`, manifest_sha256: hash(manifestBody) };
    await page.unroute('**/data/extended/latest.json');
    await page.route('**/data/extended/latest.json', route => route.fulfill({ json: newPointer }));
    await page.route(`**/data/extended/releases/${id}/manifest.json`, route => route.fulfill({ contentType: 'application/json', body: manifestBody }));
    await page.route(`**/data/extended/releases/${id}/history.json`, route => route.fulfill({ contentType: 'application/json', body }));
    await page.route(`**/data/extended/releases/${id}/research.json`, route => route.fulfill({ contentType: 'application/json', body: researchBody }));
    await page.unroute('**/data/extended/status.json');
    await page.route('**/data/extended/status.json', route => route.fulfill({ json: { ...pipelineStatus, release_id: id } }));
  }
